#!/usr/bin/env python3
"""Generate immutable HeadAudio-compatible DSP tables for embedded C."""

from __future__ import annotations

import math
import struct
from pathlib import Path

TOOLS_DIR = Path(__file__).resolve().parent
OUTPUT = TOOLS_DIR.parent / "firmware-ws" / "main" / "face_viseme_tables.inc"
FFT_SAMPLES = 512
MEL_BANDS = 40
MFCC_COEFFICIENTS = 12
LIFTER = 22


def f32(value: float) -> float:
    return struct.unpack("<f", struct.pack("<f", value))[0]


def literal(value: float) -> str:
    if value == 0:
        return "0.0f"
    rendered = f"{value:.9g}"
    if "." not in rendered and "e" not in rendered:
        rendered += ".0"
    return rendered + "f"


def array(name: str, values: list[float], columns: int = 6) -> str:
    lines = [f"static const float {name}[{len(values)}] = {{"]
    for offset in range(0, len(values), columns):
        portion = ", ".join(literal(value) for value in values[offset : offset + columns])
        lines.append(f"    {portion},")
    lines.append("};")
    return "\n".join(lines)


def main() -> int:
    hamming = [
        f32(0.54 - 0.46 * math.cos((2 * math.pi * index) / (FFT_SAMPLES - 1)))
        for index in range(FFT_SAMPLES)
    ]

    scale = math.sqrt(2 / MEL_BANDS)
    dct: list[float] = []
    for coefficient in range(1, MFCC_COEFFICIENTS + 1):
        for band in range(MEL_BANDS):
            dct.append(
                f32(
                    scale
                    * math.cos(
                        math.pi * coefficient * (band + 0.5) / MEL_BANDS
                    )
                )
            )

    lifter = [
        f32(1 + (LIFTER / 2) * math.sin(math.pi * index / LIFTER))
        for index in range(1, MFCC_COEFFICIENTS + 1)
    ]

    midpoint = (32 - 1) / 2
    fir: list[float] = []
    for index in range(32):
        x = index - midpoint
        coefficient = math.sin(2 * math.pi * 0.45 * x) / (math.pi * x)
        coefficient *= 0.54 - 0.46 * math.cos(2 * math.pi * index / 31)
        fir.append(f32(coefficient))

    stage_cos = [
        f32(math.cos(-2 * math.pi / (1 << stage)))
        for stage in range(1, 10)
    ]
    stage_sin = [
        f32(math.sin(-2 * math.pi / (1 << stage)))
        for stage in range(1, 10)
    ]

    text = "\n\n".join(
        [
            "/* Generated by tools/generate_face_viseme_tables.py. */",
            array("s_hamming", hamming),
            array("s_dct", dct),
            array("s_lifter", lifter),
            array("s_native_16k_fir", fir),
            array("s_fft_stage_cos", stage_cos),
            array("s_fft_stage_sin", stage_sin),
        ]
    )
    OUTPUT.write_text(text + "\n", encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
